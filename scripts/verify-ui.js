// Run with Playwright CLI's `run-code` command against a local dev server.
// Every booking POST is mocked; this script never creates a real booking.
async page => {
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const passed = []
  const record = name => passed.push(name)
  const hydrated = selector => page.waitForFunction(selector => !document.querySelector(selector)?.closest('astro-island')?.hasAttribute('ssr'), selector)
  const visibleDialog = () => page.getByRole('dialog')
  const first = '2026-11-10T07:00:00.000Z'
  const second = '2026-11-10T07:30:00.000Z'
  const free = { timeZone: 'Africa/Johannesburg', slots: [{ start: first, free: true }, { start: second, free: true }] }
  await page.route('**/api/book', route => route.fulfill({ status: 503, json: { error: 'unavailable' } }))
  await page.route('**/api/slots', route => route.fulfill({ json: free }))
  await page.emulateMedia({ reducedMotion: 'no-preference' })

  await page.goto('http://localhost:3000/')
  await page.evaluate(() => { sessionStorage.removeItem('cs-motion-paused'); localStorage.setItem('cs-consent', 'denied') })
  await page.reload()
  await hydrated('#header-menu')
  await page.keyboard.press('Tab')
  assert(await page.locator('.skip-link').evaluate(el => el === document.activeElement), 'Skip link must be first keyboard stop')
  await page.keyboard.press('Enter')
  assert(await page.locator('#main-content').evaluate(el => el === document.activeElement), 'Skip link must focus main')
  record('Skip link focuses main')

  for (const width of [320, 390, 768, 992, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Home overflows at ${width}px`)
    if (width <= 992) {
      await page.locator('#header-menu').click()
      assert(await visibleDialog().isVisible(), `Menu must open at ${width}px`)
      assert((await visibleDialog().boundingBox()).width >= Math.min(width, 384) - 2, 'Menu must keep its useful width')
      for (let i = 0; i < 10; i++) {
        await page.keyboard.press('Tab')
        await page.waitForFunction(() => document.querySelector('[role=dialog]')?.contains(document.activeElement))
      }
      await page.keyboard.press('Escape')
      await visibleDialog().waitFor({ state: 'hidden' })
      await page.waitForFunction(() => document.activeElement?.id === 'header-menu')
    }
  }
  record('Responsive layout and mobile menu focus at five widths')

  await page.setViewportSize({ width: 1440, height: 900 })
  await page.locator('#resources').scrollIntoViewIfNeeded()
  await hydrated('#faq-question-1')
  await page.locator('#faq-question-2').focus()
  await page.keyboard.press('Enter')
  assert(await page.locator('#faq-question-2').getAttribute('aria-expanded') === 'true', 'FAQ must open with Enter')
  await page.keyboard.press('ArrowDown')
  await page.waitForFunction(() => document.activeElement?.id === 'faq-question-3')
  record('FAQ keyboard disclosure and navigation')

  await page.locator('#credit-calculator').scrollIntoViewIfNeeded()
  await hydrated('#credit-calculator')
  const slider = page.getByRole('slider', { name: 'Social media posts: how many' })
  await slider.focus()
  await page.keyboard.press('ArrowRight')
  assert(await slider.inputValue() === '1', 'Calculator range must respond to keyboard')
  assert(await page.getByText('3 of 60 credits used', { exact: true }).count() === 1, 'Calculator must update its accessible total')
  await page.getByRole('button', { name: 'Reset mix' }).click()
  assert(await slider.inputValue() === '0', 'Reset must clear the creative mix')
  record('Calculator keyboard total and reset')

  await page.locator('#work').scrollIntoViewIfNeeded()
  const card = page.locator('[id^="work-card-"]').first()
  await hydrated('#work')
  await card.click()
  await visibleDialog().waitFor()
  await page.locator('#viewer-next-project').click()
  await page.keyboard.press('Escape')
  await visibleDialog().waitFor({ state: 'hidden', timeout: 2500 })
  await page.waitForTimeout(400)
  assert(await visibleDialog().count() === 0, 'Delayed next-project transition must not reopen a closed dialog')
  await page.waitForFunction(() => document.activeElement?.id?.startsWith('work-card-'))
  await card.click()
  await visibleDialog().waitFor()
  await page.evaluate(() => { location.hash = '#pricing' })
  await visibleDialog().waitFor({ state: 'hidden' })
  record('Portfolio next-close race, focus return and hash dismissal')

  await page.setViewportSize({ width: 390, height: 844 })
  await page.unroute('**/api/slots')
  await page.route('**/api/slots', route => route.fulfill({ json: { ...free, slots: free.slots.map(slot => ({ ...slot, free: false })) } }))
  await page.goto('http://localhost:3000/book-a-demo')
  await page.locator('#book-calendar-status').waitFor()
  assert(await page.locator('#book-date').isDisabled(), 'All-busy calendar must disable date selection')
  assert(await page.getByRole('button', { name: 'No times available' }).isDisabled(), 'All-busy calendar must disable submit')
  assert((await page.locator('#book-calendar-status').innerText()).toLowerCase().includes('email'), 'All-busy calendar must offer email recovery')
  await page.unroute('**/api/slots')
  let refreshes = 0
  await page.route('**/api/slots', route => route.fulfill({ json: ++refreshes === 1 ? free : { ...free, slots: [{ start: first, free: false }, { start: second, free: true }] } }))
  await page.getByRole('button', { name: 'Refresh times' }).click()
  await page.locator('#book-date:enabled').waitFor()
  await page.getByRole('button', { name: 'Book my demo' }).click()
  assert(await page.locator('#book-firstName').evaluate(el => el === document.activeElement), 'Validation must focus first required field')
  for (const [id, value] of Object.entries({ firstName: 'Alex', lastName: 'Demo', email: 'alex@example.com', phone: '+27 82 123 4567', company: 'Example Studio', role: 'Marketing lead' })) await page.locator(`#book-${id}`).fill(value)
  assert(await page.locator('#book-firstName').getAttribute('maxlength') === '60', 'Name length must match server')
  assert(await page.locator('#book-phone').getAttribute('maxlength') === '40', 'Phone length must match server')
  await page.locator('#book-date').click()
  assert(await page.getByRole('dialog', { name: 'Choose a demo date' }).isVisible(), 'Date picker needs an accessible name')
  await page.getByRole('button', { name: 'Tuesday 10 November', exact: true }).click()
  await page.locator('#book-slot').click()
  await visibleDialog().locator('button[aria-pressed="false"]:enabled').first().click()
  await page.getByRole('button', { name: 'Book my demo' }).click()
  await page.getByText('Your booking didn’t go through.', { exact: false }).waitFor()
  assert(await page.locator('#book-firstName').inputValue() === 'Alex', 'Submission failure must preserve entered details')
  await page.unroute('**/api/book')
  await page.route('**/api/book', route => route.fulfill({ status: 409, json: { error: 'slot_taken' } }))
  await page.getByRole('button', { name: 'Book my demo' }).click()
  await page.getByText('That time has just been taken.', { exact: false }).waitFor()
  await page.waitForFunction(() => document.activeElement?.id === 'book-slot')
  assert(await page.locator('#book-firstName').inputValue() === 'Alex', 'Conflict must preserve entered details')
  assert((await page.locator('#book-slot').innerText()).includes('Select a time'), 'Conflict must clear stale selection')
  await page.unroute('**/api/book')
  await page.route('**/api/book', route => route.fulfill({ json: { start: second, end: '2026-11-10T08:00:00.000Z', sample: true } }))
  await page.locator('#book-slot').click()
  await visibleDialog().locator('button[aria-pressed="false"]:enabled').first().click()
  await page.getByRole('button', { name: 'Book my demo' }).click()
  const confirmation = page.getByRole('heading', { name: 'See you Tuesday, Alex.' })
  await confirmation.waitFor()
  assert(await confirmation.evaluate(el => el === document.activeElement), 'Success must focus confirmation')
  assert(await page.getByText('This preview does not send', { exact: false }).isVisible(), 'Sample must not claim an invite was sent')
  record('Booking all-busy, recovery, validation, submission failure, conflict and sample confirmation')

  await page.unroute('**/api/slots')
  await page.route('**/api/slots', () => {})
  await page.goto('http://localhost:3000/book-a-demo')
  await page.getByText('We couldn’t load the calendar.', { exact: false }).waitFor({ timeout: 15_000 })
  assert(await page.locator('#book-date').isDisabled(), 'Stalled availability must fail into recoverable state')
  await page.unroute('**/api/slots')
  await page.route('**/api/slots', route => route.fulfill({ json: free }))
  await page.getByRole('button', { name: 'Try again', exact: true }).click()
  await page.locator('#book-date:enabled').waitFor()
  record('Stalled calendar times out and retries successfully')

  await page.goto('http://localhost:3000/')
  await page.getByRole('button', { name: 'Pause animations', exact: true }).click()
  assert(await page.evaluate(() => document.documentElement.dataset.animationsPaused) === 'true', 'User pause must reach the document')
  await page.reload()
  await page.getByRole('button', { name: 'Resume animations', exact: true }).waitFor()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Reduced motion on', exact: true }).waitFor()
  assert(await page.evaluate(() => [...document.querySelectorAll('video')].every(video => video.paused)), 'Reduced motion must pause ambient videos')
  record('Motion pause persists and OS preference pauses videos')

  await page.evaluate(passed => { window.qualityChecks = passed }, passed)
  console.log(JSON.stringify({ passed }))
}
